"""Deterministic paper edge-identity evidence (PRDV4 Stage 4 prerequisite, identity-only).

This validation artifact resolves a canonical, digest-bound paper ``edge_id`` for a paper evaluation from a
proven ``StrategySpec`` (and, optionally, a proven ``StrategySignalToPaperIntent`` bridge). It is paper-only,
deterministic, digest-bound, and fail-closed.

Governance (user-approved for this slice):

* ``paper_edge_id = sha256(canonical_json({"strategy_id": ..., "market_symbol": ...}))`` — a lowercase hex64,
  delimiter-free, collision-resistant digest; ``strategy_id`` and ``market_symbol`` are also bound separately as
  human-readable fields;
* the ``StrategySpec`` identity is proven by recomputing the PUBLIC ``strategy_spec_digest`` and requiring it to
  equal the caller anchor, plus a full ``validate_strategy_spec`` acceptance and a ``market_symbol`` membership
  check against the spec's ``instrument_universe``;
* an OPTIONAL ``StrategySignalToPaperIntent`` bridge upgrades the binding from
  ``STRATEGY_SPEC_DIGEST_BOUND`` to ``SPEC_DIGEST_AND_SIGNAL_BRIDGE_BOUND`` after its public digest is re-proven
  and its identity fields are cross-checked.

EXPLICIT LIMITATION (serializer-visible + digest-bound): the binding to the already-merged §10.4 / Sharpe paper
chain is ``correlation_and_market_only`` — those merged artifacts do NOT carry ``spec_digest``, so this artifact
does NOT cryptographically prove that the merged §10.4 / Sharpe chain was generated by this ``StrategySpec``.

It does NOT consume ``PaperSharpeEvidence`` / ``PaperVsBacktestMethodology`` / daily-return / 30-day-gate
evidence, does NOT bind a backtest baseline, does NOT invoke the Stage-4 comparator, does NOT construct
``Stage4PaperSummary`` / ``Stage4BacktestBaseline``, does NOT set ``prdv4_stage4_complete``, and does NOT prove
edge, profitability, comparison readiness, live readiness, shadow readiness, Deribit readiness, or operational
readiness. It calls no wall-clock, runtime, service, execution, venue, scheduler, filesystem, network, or random
surface.
"""

