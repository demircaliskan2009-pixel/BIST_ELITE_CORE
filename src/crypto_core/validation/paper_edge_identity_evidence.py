def _canonical_digest(payload: dict[str, object]) -> str:
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True, allow_nan=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _is_plain_non_empty_string(value: object) -> bool:
    return (
        type(value) is str
        and value.strip() != ""
        and value == value.strip()
        and not any(ord(char) < 32 or ord(char) == 127 for char in value)
    )


def _is_hex64_string(value: object) -> bool:
    return type(value) is str and len(value) == _SHA256_HEX_LENGTH and all(char in _HEX_CHARS for char in value)


def _require_plain_non_empty_string(value: object, field_name: str) -> str:
    if not _is_plain_non_empty_string(value):
        raise PaperEdgeIdentityEvidenceError(f"paper_edge_identity_evidence:{field_name}_invalid")
    return value  # type: ignore[return-value]


def _derive_paper_edge_id(strategy_id: str, market_symbol: str) -> str:
    canonical = json.dumps(
        {"strategy_id": strategy_id, "market_symbol": market_symbol},
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _normalize_metadata(metadata: object) -> tuple[tuple[str, str], ...]:
    if metadata is None:
        return ()
    if not isinstance(metadata, Mapping):
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:metadata_malformed")
    items: list[tuple[str, str]] = []
    for key, value in metadata.items():
        if type(key) is not str or type(value) is not str:
            raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:metadata_malformed")
        if key != key.strip() or value != value.strip() or any(ord(char) < 32 or ord(char) == 127 for char in key):
            raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:metadata_malformed")
        if any(ord(char) < 32 or ord(char) == 127 for char in value):
            raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:metadata_malformed")
        items.append((key, value))
    return tuple(sorted(items))


def _metadata_texts(metadata: tuple[tuple[str, str], ...]) -> tuple[str, ...]:
    return tuple(text for pair in metadata for text in pair)


def _serialize_metadata(metadata: tuple[tuple[str, str], ...]) -> list[list[str]]:
    return [[key, value] for key, value in metadata]


def _has_scope_violation(*texts: object) -> bool:
    for text in texts:
        if type(text) is not str or text == "":
            continue
        if _BIST_PATTERN.search(text):
            return True
        scrubbed = text
        for safe_term in _SAFE_MARKET_DATA_TERMS:
            scrubbed = re.sub(re.escape(safe_term), " ", scrubbed, flags=re.IGNORECASE)
        if _FORBIDDEN_PATTERN.search(scrubbed):
            return True
    return False


def _has_clock_token(*texts: object) -> bool:
    for text in texts:
        if type(text) is not str or text == "":
            continue
        lowered = text.lower()
        if any(token in lowered for token in _CLOCK_TOKENS):
            return True
    return False


def _str_field(value: object) -> str:
    return value if type(value) is str else ""


def _spec_hard_failures(
    strategy_spec: StrategySpec, expected_strategy_spec_digest: str, market_symbol: str
) -> list[str]:
    hard: list[str] = []
    if type(strategy_spec.market_type) is not StrategySpecMarketType or strategy_spec.market_type not in (
        _SUPPORTED_MARKET_TYPES
    ):
        hard.append("paper_edge_identity_evidence:unsupported_market_type")

    try:
        recomputed = strategy_spec_digest(strategy_spec)
    except Exception:  # noqa: BLE001 - public digest recompute failures fail closed at this boundary
        recomputed = None
    if recomputed is None or recomputed != expected_strategy_spec_digest:
        hard.append("paper_edge_identity_evidence:strategy_spec_digest_mismatch")

    try:
        validation = validate_strategy_spec(strategy_spec_to_dict(strategy_spec))
        accepted = validation.accepted is True
    except Exception:  # noqa: BLE001 - a malformed forged spec must fail closed, never crash
        accepted = False
    if not accepted:
        hard.append("paper_edge_identity_evidence:strategy_spec_invalid")

    universe = strategy_spec.instrument_universe
    if (
        type(universe) is not tuple
        or not all(type(symbol) is str for symbol in universe)
        or market_symbol not in (universe)
    ):
        hard.append("paper_edge_identity_evidence:market_symbol_not_in_universe")
    return sorted(set(hard))


def _bridge_hard_failures(
    bridge: StrategySignalToPaperIntent,
    expected_signal_bridge_digest: str,
    strategy_spec: StrategySpec,
    expected_strategy_spec_digest: str,
    market_symbol: str,
    correlation_id: str,
) -> list[str]:
    hard: list[str] = []
    try:
        recomputed = strategy_signal_to_paper_intent_digest(bridge)
    except Exception:  # noqa: BLE001 - public digest recompute failures fail closed at this boundary
        recomputed = None
    if (
        recomputed is None
        or not _is_hex64_string(bridge.bridge_digest)
        or bridge.bridge_digest != recomputed
        or bridge.bridge_digest != expected_signal_bridge_digest
    ):
        hard.append("paper_edge_identity_evidence:signal_bridge_digest_mismatch")

    if bridge.status is not StrategySignalToPaperIntentStatus.READY or bridge.ready is not True:
        hard.append("paper_edge_identity_evidence:signal_bridge_not_ready")
    if (
        bridge.real_orders_enabled is not False
        or bridge.real_money_enabled is not False
        or bridge.capital_reserved is not False
        or bridge.order_routed is not False
        or bridge.execution_authorized is not False
        or bridge.live_api_called is not False
        or bridge.scheduler_enabled is not False
        or bridge.auto_loop_enabled is not False
        or bridge.connector_invoked is not False
        or bridge.live_ready is not False
        or bridge.shadow_ready is not False
        or bridge.profitability_proven is not False
        or bridge.edge_proven is not False
    ):
        hard.append("paper_edge_identity_evidence:signal_bridge_unsafe_flags")

    if bridge.strategy_id != strategy_spec.strategy_id:
        hard.append("paper_edge_identity_evidence:signal_bridge_strategy_id_mismatch")
    if bridge.strategy_version != strategy_spec.strategy_version:
        hard.append("paper_edge_identity_evidence:signal_bridge_strategy_version_mismatch")
    if bridge.spec_digest != expected_strategy_spec_digest:
        hard.append("paper_edge_identity_evidence:signal_bridge_spec_digest_mismatch")
    if bridge.correlation_id != correlation_id:
        hard.append("paper_edge_identity_evidence:signal_bridge_correlation_id_mismatch")
    if bridge.market_symbol != market_symbol:
        hard.append("paper_edge_identity_evidence:signal_bridge_market_symbol_mismatch")
    return sorted(set(hard))


def build_paper_edge_identity_evidence(
    strategy_spec: StrategySpec,
    *,
    expected_strategy_spec_digest: str,
    market_symbol: str,
    edge_identity_id: str,
    paper_id: str,
    correlation_id: str,
    signal_to_paper_intent: StrategySignalToPaperIntent | None = None,
    expected_signal_bridge_digest: str | None = None,
    metadata: Mapping[str, str] | None = None,
) -> PaperEdgeIdentityEvidence:
    """Resolve a deterministic, digest-bound paper edge identity from a proven StrategySpec (+ optional bridge)."""

    if type(strategy_spec) is not StrategySpec:
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:strategy_spec_malformed")
    if not _is_hex64_string(expected_strategy_spec_digest):
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:expected_strategy_spec_digest_invalid")
    market_symbol = _require_plain_non_empty_string(market_symbol, "market_symbol")
    edge_identity_id = _require_plain_non_empty_string(edge_identity_id, "edge_identity_id")
    paper_id = _require_plain_non_empty_string(paper_id, "paper_id")
    correlation_id = _require_plain_non_empty_string(correlation_id, "correlation_id")

    bridge_supplied = signal_to_paper_intent is not None
    if bridge_supplied:
        if type(signal_to_paper_intent) is not StrategySignalToPaperIntent:
            raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:signal_to_paper_intent_malformed")
        if not _is_hex64_string(expected_signal_bridge_digest):
            raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:expected_signal_bridge_digest_invalid")
    elif expected_signal_bridge_digest is not None:
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:expected_signal_bridge_digest_unexpected")

    metadata_pairs = _normalize_metadata(metadata)
    scope_texts = (market_symbol, edge_identity_id, paper_id, correlation_id, *_metadata_texts(metadata_pairs))
    if _has_scope_violation(*scope_texts):
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:scope_violation")
    if _has_clock_token(*scope_texts):
        raise PaperEdgeIdentityEvidenceError("paper_edge_identity_evidence:clock_token_forbidden")

    hard = _spec_hard_failures(strategy_spec, expected_strategy_spec_digest, market_symbol)
    if bridge_supplied:
        hard.extend(
            _bridge_hard_failures(
                signal_to_paper_intent,  # type: ignore[arg-type]
                expected_signal_bridge_digest,  # type: ignore[arg-type]
                strategy_spec,
                expected_strategy_spec_digest,
                market_symbol,
                correlation_id,
            )
        )
    hard = sorted(set(hard))

    strategy_id = _str_field(strategy_spec.strategy_id)
    if hard:
        status = PaperEdgeIdentityEvidenceStatus.REJECTED
        ready = False
        reason_codes = tuple(hard)
        paper_edge_id = ""
        verified_strategy_spec_digest = ""
        verified_signal_bridge_digest = ""
        binding_strength = _BINDING_UNRESOLVED
        signal_bridge_consumed = False
    else:
        status = PaperEdgeIdentityEvidenceStatus.READY
        ready = True
        reason_codes = ()
        paper_edge_id = _derive_paper_edge_id(strategy_id, market_symbol)
        verified_strategy_spec_digest = expected_strategy_spec_digest
        signal_bridge_consumed = bridge_supplied
        if bridge_supplied:
            binding_strength = _BINDING_SPEC_AND_BRIDGE
            verified_signal_bridge_digest = expected_signal_bridge_digest  # type: ignore[assignment]
        else:
            binding_strength = _BINDING_SPEC_ONLY
            verified_signal_bridge_digest = ""

    signal_bridge_digest = _str_field(signal_to_paper_intent.bridge_digest) if bridge_supplied else ""

    fields: dict[str, object] = {
        "schema_version": _SCHEMA_VERSION,
        "evidence_version": _EVIDENCE_VERSION,
        "status": status,
        "ready": ready,
        "edge_identity_id": edge_identity_id,
        "paper_id": paper_id,
        "correlation_id": correlation_id,
        "edge_identity_resolved": ready,
        "strategy_spec_identity_proven": ready,
        "signal_bridge_consumed": signal_bridge_consumed,
        "paper_edge_id": paper_edge_id,
        "edge_id_form": _EDGE_ID_FORM,
        "edge_id_derivation_policy": _EDGE_ID_DERIVATION_POLICY,
        "edge_id_derivation_inputs": _EDGE_ID_DERIVATION_INPUTS,
        "strategy_id": strategy_id,
        "strategy_version": _str_field(strategy_spec.strategy_version),
        "strategy_family": _str_field(strategy_spec.strategy_family),
        "edge_family": _str_field(strategy_spec.edge_family),
        "market_type": strategy_spec.market_type.value
        if type(strategy_spec.market_type) is StrategySpecMarketType
        else "",
        "market_symbol": market_symbol,
        "expected_strategy_spec_digest": expected_strategy_spec_digest,
        "verified_strategy_spec_digest": verified_strategy_spec_digest,
        "signal_bridge_digest": signal_bridge_digest,
        "expected_signal_bridge_digest": expected_signal_bridge_digest if bridge_supplied else "",
        "verified_signal_bridge_digest": verified_signal_bridge_digest,
        "binding_strength": binding_strength,
        "paper_chain_link": _PAPER_CHAIN_LINK,
        "paper_chain_link_cryptographic": False,
        "paper_chain_spec_digest_carried": False,
        "paper_chain_link_limitation": _PAPER_CHAIN_LINK_LIMITATION,
        "reason_codes": reason_codes,
        "metadata": metadata_pairs,
    }
    seed = PaperEdgeIdentityEvidence(edge_identity_digest="", **fields)  # type: ignore[arg-type]
    return _replace_evidence_digest(seed, paper_edge_identity_evidence_digest(seed))


def _replace_evidence_digest(evidence: PaperEdgeIdentityEvidence, digest: str) -> PaperEdgeIdentityEvidence:
    fields = _evidence_fields(evidence)
    fields["edge_identity_digest"] = digest
    return PaperEdgeIdentityEvidence(**fields)  # type: ignore[arg-type]


